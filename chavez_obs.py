import numpy as np
import matplotlib.pyplot as plt

def plot_time_gaps(data):
    plt.figure()

    for obs, filters in data.items():
        for filt, jd in filters.items():
            jd_sorted = np.sort(jd)
            dt = np.diff(jd_sorted)  # time gaps in days

            label = f"{obs} - {filt}"
            plt.plot(dt, marker='o', linestyle='-', label=label)

    plt.xlabel("Observation Index")
    plt.ylabel("Δt (days)")
    plt.title("Time Between Consecutive Observations")
    plt.legend()
    plt.grid()
    plt.show()

def plot_observation_times(data):
    plt.figure()

    y_offset = 0
    yticks = []
    ylabels = []

    for obs, filters in data.items():
        for filt, jd in filters.items():
            jd_sorted = np.sort(jd)
            
            y = np.ones_like(jd_sorted) * y_offset
            plt.scatter(jd_sorted, y, label=f"{obs} - {filt}")

            yticks.append(y_offset)
            ylabels.append(f"{obs}-{filt}")
            y_offset += 1

    plt.xlabel("Julian Date")
    plt.yticks(yticks, ylabels)
    plt.title("NIR Observation Timeline")
    plt.grid()
    plt.legend()
    plt.show()

def plot_gap_histograms(data):
    plt.figure()

    for obs, filters in data.items():
        for filt, jd in filters.items():
            jd_sorted = np.sort(jd)
            dt = np.diff(jd_sorted)

            plt.hist(dt, bins=20, alpha=0.5, label=f"{obs}-{filt}")

    plt.xlabel("Δt (days)")
    plt.ylabel("Count")
    plt.title("Distribution of Observation Gaps")
    plt.legend()
    plt.grid()
    plt.show()


